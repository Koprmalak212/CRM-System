<?php
declare(strict_types=1);

// Creates the ops_console database in MariaDB and seeds it with FAKE data.
// Run once:  C:\xampp\php\php.exe bin/setup.php   (CLI only; re-running resets all data)

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit('Run this from the command line: php bin/setup.php');
}

const DB_HOST = '127.0.0.1';
const DB_NAME = 'ops_console';
const DB_USER = 'root';
const DB_PASS = '';
const ADMIN_USERNAME = 'admin';
const ADMIN_EMAIL = 'admin@telecomlijn.test';
const ADMIN_PASSWORD = 'admin';

$demo = in_array('--demo', $argv ?? [], true);    // seed fake demo data
$reset = in_array('--reset', $argv ?? [], true);  // allow dropping an existing database
$wipe = in_array('--wipe-all', $argv ?? [], true);  // with --reset: also delete saved API keys, the Kuma connection and endpoints
$pdo = new PDO('mysql:host=' . DB_HOST . ';charset=utf8mb4', DB_USER, DB_PASS, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$exists = (bool) $pdo->query("SHOW DATABASES LIKE '" . DB_NAME . "'")->fetchColumn();
if ($exists && !$reset) {
    fwrite(STDERR, "The database '" . DB_NAME . "' already exists. Running setup again DELETES everything in it (accounts, invoices, logs). Your Kuma connection, API keys and endpoints are kept; add --wipe-all to delete those too.
If you really want that, run:  php bin/setup.php --reset" . ($demo ? ' --demo' : '') . "
");
    exit(1);
}
// A reset keeps the connection settings that took effort to enter: the Kuma connection, the health-API keys and
// your own endpoints and test-log entries (demo rows are not kept). Add --wipe-all to remove them too.
$keep = [];
if ($exists && !$wipe) {
    $pdo->exec('USE `' . DB_NAME . '`');
    foreach (['kuma_settings' => '1 = 1', 'api_keys' => '1 = 1', 'monitored_endpoints' => 'is_demo = 0', 'test_log' => "source = 'manual'"] as $t => $where) {
        try { $keep[$t] = $pdo->query("SELECT * FROM `$t` WHERE $where")->fetchAll(PDO::FETCH_ASSOC); }
        catch (Throwable $e) { $keep[$t] = []; }
    }
}
$pdo->exec('DROP DATABASE IF EXISTS `' . DB_NAME . '`');
$pdo->exec('CREATE DATABASE `' . DB_NAME . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
$pdo->exec('USE `' . DB_NAME . '`');
$pdo->exec("SET time_zone = '" . date('P') . "'");
$pdo->exec(file_get_contents(__DIR__ . '/../database/schema.sql'));


// Least-privilege database account for the web app (never root). Credentials go to includes/config.local.php, which is git-ignored and blocked by .htaccess.
$appPass = bin2hex(random_bytes(16));
foreach (['127.0.0.1', 'localhost'] as $h) {
    $pdo->exec("DROP USER IF EXISTS 'ops_console_app'@'$h'");
    $pdo->exec("CREATE USER 'ops_console_app'@'$h' IDENTIFIED BY '$appPass'");
    $pdo->exec("GRANT SELECT, INSERT, UPDATE, DELETE ON `" . DB_NAME . "`.* TO 'ops_console_app'@'$h'");
}
$pdo->exec('FLUSH PRIVILEGES');
$oldConfig = (!$wipe && is_file(__DIR__ . '/../includes/config.local.php')) ? (require __DIR__ . '/../includes/config.local.php') : [];
$appKey = (string) ($oldConfig['app_key'] ?? '');   // reused, so secrets saved before the reset can still be decrypted
if (strlen((string) base64_decode($appKey)) !== 32) { $appKey = base64_encode(random_bytes(32)); }   // encrypts stored API secrets (AES-256-GCM)
file_put_contents(
    __DIR__ . '/../includes/config.local.php',
    "<?php\n// Generated by bin/setup.php. Do not commit.\nreturn " . var_export([
        'db_host' => DB_HOST, 'db_name' => DB_NAME, 'db_user' => 'ops_console_app', 'db_pass' => $appPass,
        'app_key' => $appKey,                // encrypts stored API secrets
        'allow_private_targets' => false,    // health checks may only call public addresses (SSRF protection)
    ], true) . ";\n"
);

// Admin
$pdo->prepare("INSERT INTO admins (username, email, name, password_hash, role, perm_integrations, avatar, must_change_password) VALUES (?, ?, ?, ?, 'admin', 'manage', 'assets/avatars/oia-cat.gif', 0)")
    ->execute([ADMIN_USERNAME, ADMIN_EMAIL, 'Denis Mehmed', (defined('PASSWORD_ARGON2ID') ? password_hash(ADMIN_PASSWORD, PASSWORD_ARGON2ID) : password_hash(ADMIN_PASSWORD, PASSWORD_BCRYPT, ['cost' => 12]))]);
$restored = [];
foreach ($keep as $t => $rows) {
    foreach ($rows as $r) {
        $cols = array_keys($r);
        $pdo->prepare('INSERT INTO `' . $t . '` (`' . implode('`,`', $cols) . '`) VALUES (' . implode(',', array_fill(0, count($cols), '?')) . ')')->execute(array_values($r));
    }
    if ($rows) { $restored[] = count($rows) . ' ' . str_replace('_', ' ', $t); }
}
$supportPass = null;
if ($demo) {
    // A normal (non-admin) demo account to try the permission model. Random password, printed once below.
    $supportPass = bin2hex(random_bytes(6)) . '-Aa1!';
    $pdo->prepare("INSERT INTO admins (username, email, name, password_hash, role, perm_integrations) VALUES ('support', 'support@telecomlijn.test', 'Noor Haddad', ?, 'user', 'none')")
        ->execute([defined('PASSWORD_ARGON2ID') ? password_hash($supportPass, PASSWORD_ARGON2ID) : password_hash($supportPass, PASSWORD_BCRYPT, ['cost' => 12])]);
    require __DIR__ . '/../includes/modules/demo.php';   // the same loader the Overview button uses
    demo_seed($pdo);
}

if ($restored) { echo 'Kept: ' . implode(', ', $restored) . " (use --wipe-all to remove these too).\n"; }
echo "Done. Database '" . DB_NAME . "' created" . ($demo ? " and seeded with FAKE demo data" : " (empty: only the admin account)") . ".
";
if ($supportPass !== null) { echo "Normal demo account: support / $supportPass (no integrations access until an admin grants it)
"; }
echo 'Sign in at http://localhost/Websites/test/login.php with username ' . ADMIN_USERNAME . ' and password ' . ADMIN_PASSWORD . "
";
